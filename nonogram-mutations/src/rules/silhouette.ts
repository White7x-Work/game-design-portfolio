export const TEMPLATES: Record<string, SilhouetteTemplate> = {};

function def(id: string, name: string, rows: string[]): void {
  for (const r of rows) {
    if (r.length !== rows[0].length) throw new Error(`template ${id}: row width mismatch`);
  }
  TEMPLATES[id] = { id, name, rows };
}

