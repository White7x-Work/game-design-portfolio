// 剪影模板库 — 规格 §2.5 / §7.5
// 模板为小型像素画：'.'=空，'#'=填色1（黑白），'1'..'5'=彩色 id。
// 剪影关卡不改变规则，只改变解的内容（动物/物件剪影）。
import type { Matrix } from '../core/grid.js';
import type { RNG } from '../core/prng.js';

export interface SilhouetteTemplate {
  id: string;
  name: string;
  /** 每行等长；字符集 '.' '#' '1'-'5' */
  rows: string[];
}

export function tplHeight(t: SilhouetteTemplate): number {
  return t.rows.length;
}
export function tplWidth(t: SilhouetteTemplate): number {
  return t.rows[0].length;
}

/** 模板 → 矩阵（'#' 视为 1） */
export function templateToMatrix(t: SilhouetteTemplate): Matrix {
  return t.rows.map((r) => r.split('').map((ch) => (ch === '.' ? 0 : ch === '#' ? 1 : parseInt(ch, 10))));
}

