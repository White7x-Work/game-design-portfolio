export function getTemplate(id: string): SilhouetteTemplate {
  const t = TEMPLATES[id];
  if (!t) throw new Error('unknown template: ' + id);
  return t;
}

/** 把模板确定性放置到 w×h 网格。空隙尽量两侧均分（奇数空隙随机选侧），
 *  避免换出/生成大片空白行/列；只做水平镜像、不做垂直翻转（倒置破坏可辨识度，§11）。 */
export function placeTemplate(
  t: SilhouetteTemplate,
  w: number,
  h: number,
  rng: RNG
): Matrix | null {
  const tw = tplWidth(t);
  const th = tplHeight(t);
  if (tw > w || th > h) return null;
  let rows = t.rows;
  // 随机水平镜像（剪影镜像不改变可辨识度）
  if (rng() < 0.5) rows = rows.map((r) => r.split('').reverse().join(''));
  // 居中偏置：偶数空隙两侧均分；奇数空隙多出的 1 格随机放某一侧
  const splitSlack = (slack: number): number =>
    slack <= 0 ? 0 : slack % 2 === 0 ? slack / 2 : Math.floor(slack / 2) + (rng() < 0.5 ? 0 : 1);
  const ox = splitSlack(w - tw);
  const oy = splitSlack(h - th);
  const g: Matrix = [];
  for (let y = 0; y < h; y++) {
    const row: number[] = new Array(w).fill(0);
    const ty = y - oy;
    if (ty >= 0 && ty < th) {
      const src = rows[ty];
      for (let x = 0; x < w; x++) {
        const tx = x - ox;
        if (tx >= 0 && tx < tw) {
          const ch = src[tx];
          row[x] = ch === '.' ? 0 : ch === '#' ? 1 : parseInt(ch, 10);
        }
      }
    }
    g.push(row);
  }
  return g;
}

