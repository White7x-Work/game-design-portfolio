// dev 工具：程序化生成全部 50 关内嵌解 + 独立唯一解校验 + ASCII 预览
// 用法：npm run build && node tools/gen-levels.mjs [--preview] [--only m01,c03]
import { MAINLINE_SPECS } from '../build/levels/mainline.js';
import { CHALLENGE_SPECS } from '../build/levels/challenge.js';
import { generateLevel } from '../build/core/generator.js';
import { countSolutions } from '../build/core/solver.js';
import { mulberry32, hashString } from '../build/core/prng.js';
import { gridToStrings, gridToAscii } from '../build/core/grid.js';
import { writeFileSync } from 'node:fs';

const preview = process.argv.includes('--preview');
const onlyIdx = process.argv.indexOf('--only');
const only = onlyIdx >= 0 ? process.argv[onlyIdx + 1].split(',') : null;

const specs = [...MAINLINE_SPECS, ...CHALLENGE_SPECS].filter((s) => !only || only.includes(s.id));
const out = {};
const report = [];
const failed = [];
const ascpis = [];

for (const spec of specs) {
  const rng = mulberry32(hashString(spec.id));
  const t0 = Date.now();
  const res = generateLevel(spec, rng);
  const ms = Date.now() - t0;
  if (!res.level) {
    failed.push(spec.id);
    report.push(`[FAIL] ${spec.id} ${spec.width}x${spec.height} ${spec.kind} — 超预算 ${res.iters} iters (${ms}ms)`);
    continue;
  }
  // 独立复核唯一解（§7.3：计数到 2 为止；尺寸按实际关卡——剪影/挑战为裁边后的紧网格）
  const k = spec.colors ? Math.max(...spec.colors) : 1;
  const cnt = countSolutions(res.level.width, res.level.height, res.level.clues, k, { limit: 2 });
  if (cnt.count !== 1 || cnt.budgetExceeded) {
    failed.push(spec.id);
    report.push(`[FAIL] ${spec.id} — 解计数=${cnt.count}（必须=1）(${ms}ms)`);
    continue;
  }
  out[spec.id] = gridToStrings(res.level.solution);
  const filled = out[spec.id].join('').split('').filter((c) => c !== '0').length;
  const sizeStr =
    res.level.width === spec.width && res.level.height === spec.height
      ? `${String(spec.width).padStart(2)}x${spec.height}`
      : `${String(res.level.width).padStart(2)}x${res.level.height}(裁)`;
  report.push(
    `[ok] ${spec.id} ${sizeStr} ${spec.kind.padEnd(10)}` +
      ` iters=${String(res.iters).padStart(4)} lb=${String(res.loadBearing ?? '-').padEnd(5)}` +
      ` fill=${((filled / (res.level.width * res.level.height)) * 100).toFixed(0)}% ${ms}ms`
  );
  if (preview) ascpis.push(`--- ${spec.id} ${spec.title ?? ''} ---\n` + gridToAscii(res.level.solution));
}

if (!only) {
  const ts =
    '// AUTO-GENERATED by tools/gen-levels.mjs — DO NOT EDIT\n' +
    '// 每关的内嵌唯一解（程序化生成产物，dev 期经唯一解校验）。\n' +
    "// key = 关卡 id；value = H 行字符串，每字符一格（'0'=空，'1'..'5'=颜色）。\n" +
    'export const SOLUTIONS: Record<string, string[]> = {\n' +
    Object.entries(out)
      .map(([id, rows]) => `  ${JSON.stringify(id)}: [${rows.map((r) => JSON.stringify(r)).join(', ')}],`)
      .join('\n') +
    '\n};\n';
  writeFileSync(new URL('../src/levels/solutions.ts', import.meta.url), ts);
  report.push(`\nwrote src/levels/solutions.ts (${Object.keys(out).length} levels)`);
}

console.log(report.join('\n'));
if (preview) console.log('\n' + ascpis.join('\n\n'));
if (failed.length) {
  console.error('\nFAILED levels:', failed.join(', '));
  process.exit(1);
}
